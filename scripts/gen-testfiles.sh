#!/bin/bash
# 手動テスト用の altodo ファイルを testfiles/generated/ に生成する。
# 使い方: scripts/gen-testfiles.sh [--lines N]
#   test-dates-relative.altodo: 今日を基準にした日付（期日超過、今日、今週末など）
#   test-large.altodo: 約 N 行（既定 5000）のファイル（性能と表示の確認用）
# 日付は GNU date で計算する。生成物は .gitignore の対象である。

readonly OUT_DIR="testfiles/generated"

err() {
  echo "[$(date +'%Y-%m-%dT%H:%M:%S%z')]: $*" >&2
}

# 今日から $1 日後の日付を YYYY-MM-DD で出力する。
day() {
  date -d "$1 days" +%F
}

generate_dates() {
  local week_end month_end
  week_end="$(day $((7 - $(date +%u))))"
  month_end="$(date -d "$(date +%Y-%m-01) +1 month -1 day" +%F)"
  cat <<DATES
# Relative Dates Test (generated on $(date +%F))

Generated by scripts/gen-testfiles.sh. Dates are relative to that day.

## Start Dates

[ ] Started 30 days ago $(day -30) ->
[ ] Started 3 days ago $(day -3) ->
[ ] Starts today $(day 0) ->
[ ] Starts tomorrow $(day 1) ->
[ ] Starts in 7 days $(day 7) ->

## Due Dates

[ ] Overdue by 5 days -> $(day -5)
[ ] Overdue by 1 day -> $(day -1)
[ ] Due today -> $(day 0)
[ ] Due tomorrow -> $(day 1)
[ ] Due in 3 days -> $(day 3)
[ ] Due in 7 days -> $(day 7)
[ ] Due in 30 days -> $(day 30)

## Ranges

[ ] In progress window $(day -3) -> $(day 3)
[ ] Not started yet $(day 2) -> $(day 9)
[ ] Already overdue $(day -10) -> $(day -2)

## Week and Month Boundaries (week starts on Monday)

[ ] Due on the last day of this week -> ${week_end}
[ ] Due on the first day of next week -> $(date -d "${week_end} +1 day" +%F)
[ ] Due on the last day of this month -> ${month_end}
[ ] Due on the first day of next month -> $(date -d "${month_end} +1 day" +%F)
[ ] Starts on the last day of this month ${month_end} ->

## Done and Cancelled (overdue but finished)

[x] Finished late -> $(day -5) #done:$(day -1)T09:00:00+09:00
[~] Cancelled -> $(day -5) #done:$(day -2)T09:00:00+09:00
DATES
}

generate_large() {
  awk -v lines="$1" 'BEGIN {
    split(" |x|@|w|~", states, "|")
    split("alice bob carol", people, " ")
    split("work bug feature docs", tags, " ")
    print "# Large File (" lines " lines)\n"
    print "[ ] Task with a 150-line comment"
    for (i = 1; i <= 150; i++) printf "    comment line %d\n", i
    count = 153
    section = 0
    while (count < lines) {
      section++
      printf "\n## Section %d\n\n", section
      count += 4
      for (i = 1; i <= 46 && count < lines; i++) {
        flag = (i % 7 == 0) ? "! " : ""
        due = (i % 3 == 0) ? " -> 2099-12-31" : ""
        printf "[%s] %stask %d-%d #%s @%s%s\n", states[i % 5 + 1], flag,
               section, i, tags[i % 4 + 1], people[i % 3 + 1], due
        count++
        if (i % 5 == 0) { print "    description of the task"; count++ }
        if (i % 10 == 0) {
          printf "    [ ] subtask of %d-%d\n", section, i
          count++
        }
      }
    }
  }'
}

main() {
  local lines=5000

  if [[ "${1:-}" == "--lines" ]]; then
    lines="${2:?--lines needs a value}"
  fi
  mkdir -p "${OUT_DIR}" || return 1
  generate_dates >"${OUT_DIR}/test-dates-relative.altodo" || return 1
  generate_large "${lines}" >"${OUT_DIR}/test-large.altodo" || return 1
  wc -l "${OUT_DIR}"/*.altodo
}

main "$@"
